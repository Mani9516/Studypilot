/**
 * @param {number} classLevel
 * @param {string} subject
 * @param {number} chapter 1-8
 * @param {string|null} title
 */
export function resolveChapterVideoId(classLevel, subject, chapter, title) {
  const c = Number(classLevel)
  const ch = Number(chapter) || 1
  const key = `${c}|${subject}|${ch}`

  if (CLASS_CHAPTER_VIDEO[key]) return CLASS_CHAPTER_VIDEO[key]
  if (title && TOPIC_VIDEO_BY_TITLE[title]) return TOPIC_VIDEO_BY_TITLE[title]

  const rules = SUBJECT_RULES[subject] ?? SUBJECT_RULES.Mathematics
  const t = title ?? ''
  for (const [re, id] of rules) {
    if (re.test(t)) return id
  }

  return SUBJECT_DEFAULT[subject] ?? SUBJECT_DEFAULT.Mathematics
}
