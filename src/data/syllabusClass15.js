/**
 * @returns {string|null} Chapter title for class 1–5, or null if out of range.
 */
export function getClass15ChapterTitle(classLevel, subject, chapter) {
  const c = Number(classLevel)
  if (c < 1 || c > 5) return null
  const byClass = CHAPTER_TITLES_15[c]
  if (!byClass) return null
  const list = byClass[subject]
  if (!list || !list.length) return null
  const idx = Math.min(Math.max(Number(chapter) || 1, 1), 8) - 1
  return list[idx] ?? null
}
