/**
 * @returns {string|null} Chapter title for class 6–12, or null if out of range / unknown subject.
 */
export function getClass612ChapterTitle(classLevel, subject, chapter) {
  const c = Number(classLevel)
  if (c < 6 || c > 12) return null
  const byClass = CHAPTER_TITLES_612[c]
  if (!byClass) return null
  const list = byClass[subject]
  if (!list || !list.length) return null
  const idx = Math.min(Math.max(Number(chapter) || 1, 1), 8) - 1
  return list[idx] ?? null
}
